// Shared boilerplate for sumi integration test programs.
//
// Each `data/<name>.rs` is a stand-alone single-file Rust program built into
// a static Linux ELF by `build.rs`. They all `include!("common.rs")` to pull
// in raw syscall wrappers, formatting helpers, the panic handler, and a
// `check!()` macro that exits the program with a non-zero status on failure.
//
// A test passes if it reaches `pass!()` (which exits with code 0). The kernel
// prints `[exit] code=N` and the host harness greps for `[exit] code=0`.

use core::arch::{asm, global_asm};
use core::panic::PanicInfo;

// `_start` shim. The Linux x86_64 ABI hands `_start` a 16-byte aligned `rsp`
// pointing at argc, but rustc compiles `extern "C" fn _start()` assuming the
// function-call ABI (`(rsp+8) % 16 == 0`), which is one off from what the
// kernel provides. The first SSE store generated by rustc then `#GP`s on
// the misaligned stack. We sidestep the whole thing with an asm shim that
// aligns rsp and tail-calls `sumi_main`. Tests define `sumi_main` and exit
// via the `pass!()` / `check!()` macros at any point.
global_asm!(
    ".global _start",
    "_start:",
    "    xor rbp, rbp",
    "    and rsp, -16",
    "    call sumi_main",
    "    mov rdi, rax",
    "    mov rax, 231", // exit_group
    "    syscall",
    "    ud2",
);

// Each test program implements `sumi_main` (declared by the test file as
// `pub extern "C" fn sumi_main() -> i32`). The asm `_start` shim above
// references it by symbol name; no Rust extern declaration needed.

// ── raw syscall ────────────────────────────────────────────────────────────

macro_rules! syscall_fn {
    ($name:ident($($arg:ident),*) [$($operand:tt)*]) => {
        #[inline]
        unsafe fn $name(nr: u64, $($arg: u64),*) -> i64 {
            let ret: i64;
            unsafe {
                asm!(
                    "syscall",
                    inlateout("rax") nr => ret,
                    $($operand)*
                    out("rcx") _,
                    out("r11") _,
                    options(nostack),
                );
            }
            ret
        }
    };
}

syscall_fn!(syscall0() []);
syscall_fn!(syscall1(a0) [in("rdi") a0,]);
syscall_fn!(syscall2(a0, a1) [in("rdi") a0, in("rsi") a1,]);
syscall_fn!(syscall3(a0, a1, a2) [in("rdi") a0, in("rsi") a1, in("rdx") a2,]);
syscall_fn!(
    syscall4(a0, a1, a2, a3) [in("rdi") a0, in("rsi") a1, in("rdx") a2, in("r10") a3,]
);
syscall_fn!(
    syscall5(a0, a1, a2, a3, a4) [
        in("rdi") a0,
        in("rsi") a1,
        in("rdx") a2,
        in("r10") a3,
        in("r8") a4,
    ]
);
syscall_fn!(
    syscall6(a0, a1, a2, a3, a4, a5) [
        in("rdi") a0,
        in("rsi") a1,
        in("rdx") a2,
        in("r10") a3,
        in("r8") a4,
        in("r9") a5,
    ]
);

