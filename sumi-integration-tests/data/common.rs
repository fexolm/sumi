#[inline]
fn print(s: &[u8]) {
    let _ = sys_write(1, s);
}

fn print_int(mut n: i64) {
    let mut buf = [0u8; 24];
    let mut i = buf.len();
    let neg = n < 0;
    if neg {
        n = -n;
    }
    if n == 0 {
        i -= 1;
        buf[i] = b'0';
    } else {
        while n > 0 {
            i -= 1;
            buf[i] = b'0' + (n % 10) as u8;
            n /= 10;
        }
    }
    if neg {
        i -= 1;
        buf[i] = b'-';
    }
    print(&buf[i..]);
}

// ── failure helpers ────────────────────────────────────────────────────────

#[allow(unused_macros)]
macro_rules! fail {
    ($($arg:tt)*) => {{
        print(b"FAIL: ");
        $(print($arg);)*
        print(b"\n");
        exit(1);
    }};
}

#[allow(unused_macros)]
macro_rules! check {
    ($cond:expr) => {
        if !$cond {
            print(b"FAIL: ");
            print(stringify!($cond).as_bytes());
            print(b"\n");
            exit(1);
        }
    };
    ($cond:expr, $msg:expr) => {
        if !$cond {
            print(b"FAIL: ");
            print($msg);
            print(b": ");
            print(stringify!($cond).as_bytes());
            print(b"\n");
            exit(1);
        }
    };
}

#[allow(unused_macros)]
macro_rules! check_eq {
    ($left:expr, $right:expr) => {{
        let l = $left as i64;
        let r = $right as i64;
        if l != r {
            print(b"FAIL: ");
            print(stringify!($left).as_bytes());
            print(b" = ");
            print_int(l);
            print(b" != ");
            print_int(r);
            print(b" (");
            print(stringify!($right).as_bytes());
            print(b")\n");
            exit(1);
        }
    }};
}

#[allow(unused_macros)]
macro_rules! pass {
    () => {
        exit(0)
    };
}

